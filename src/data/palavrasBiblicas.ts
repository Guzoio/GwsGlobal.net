/**
 * Obtém a palavra bíblica do dia com base na data do calendário (muda automaticamente a cada dia)
 */
export function obterPalavraDoDia(data: Date = new Date()): PalavraBiblica {
  const inicioAno = new Date(data.getFullYear(), 0, 1);
  const diffDias = Math.floor((data.getTime() - inicioAno.getTime()) / (1000 * 60 * 60 * 24));
  const indice = Math.abs(diffDias) % PALAVRAS_BIBLICAS.length;
  return PALAVRAS_BIBLICAS[indice];
}

/**
 * Formata a data atual em português elegante (ex: "7 de outubro")
 */
export function formatarDataHojeExtenso(data: Date = new Date()): string {
  try {
    return new Intl.DateTimeFormat('pt-BR', {
      day: 'numeric',
      month: 'long',
    }).format(data);
  } catch {
    return 'Hoje';
  }
}
